-- =====================================================================================================================
-- 1. Exchange-rate table
--
--    Grain / PK : (rate_type, from_currency, to_currency, rate_month)
--    Convention : `rate` is expressed as units of `to_currency` per 1 unit of `from_currency`,
--                 so a converted amount is simply  amount * rate.
--    Identity   : rows where from_currency = to_currency always have rate = 1.
--
--    Rates are REAL historical data from the US Federal Reserve H.10 release (via the public
--    datasets/exchange-rates dataset), covering 1992-01 .. 1998-12 - the full TPC-H `orders` date range.
--    Six currencies are covered, one per TPC-H region (see orders_currency below):
--
--      USD  AMERICA      identity (factor 1.0)
--      EUR  EUROPE       euro did not exist before 1999, so it is proxied by the German Mark (DEM):
--                        EUR/USD = (DEM per USD) / 1.95583  (the irrevocable euro conversion rate).
--                        DEM has no daily series, so EUR EOP = EUR AVG.
--      GBP  (United Kingdom, carved out of EUROPE)   real AVG + real EOP
--      JPY  ASIA         real AVG + real EOP
--      ZAR  AFRICA       real AVG + real EOP
--      SAR  MIDDLE EAST  hard-pegged to USD at 3.75 since 1986, so SAR AVG = SAR EOP = 3.75.
--
--    The `rate` for every currency PAIR is derived by TRIANGULATION from these per-USD factors
--    (rate = to_factor / from_factor), which keeps the input data to real published per-USD rates
--    and guarantees triangular consistency across all pairs. AVG = monthly-average rate; EOP = last
--    daily observation of the month (end-of-period / spot).
-- =====================================================================================================================

