-- =====================================================================================================================
-- 3. Orders enriched with a source currency mapped from the customer's TPC-H region
--
--    Each order's source currency is derived from the customer's region via the standard TPC-H join path
--    (orders -> customer -> nation -> region). The United Kingdom is carved out to GBP; every other country
--    takes its region's currency. This maps each order to a real currency (at least at region granularity)
--    instead of an arbitrary per-customer assignment.
--
--      AMERICA -> USD    EUROPE -> EUR (UNITED KINGDOM -> GBP)    ASIA -> JPY    AFRICA -> ZAR    MIDDLE EAST -> SAR
--
--    `o_totalprice` is treated as being denominated in this source currency (a demo convenience - TPC-H prices
--    are really all in one currency).
-- =====================================================================================================================

CREATE OR REPLACE TABLE orders_currency AS
SELECT
  o.*,
  CASE
    WHEN n.n_name = 'UNITED KINGDOM' THEN 'GBP'
    WHEN r.r_name = 'AMERICA'        THEN 'USD'
    WHEN r.r_name = 'EUROPE'         THEN 'EUR'
    WHEN r.r_name = 'ASIA'           THEN 'JPY'
    WHEN r.r_name = 'AFRICA'         THEN 'ZAR'
    WHEN r.r_name = 'MIDDLE EAST'    THEN 'SAR'
  END AS source_currency
FROM orders o
JOIN customer c ON o.o_custkey    = c.c_custkey
JOIN nation   n ON c.c_nationkey  = n.n_nationkey
JOIN region   r ON n.n_regionkey  = r.r_regionkey;

ALTER TABLE orders_currency ALTER COLUMN o_orderkey SET NOT NULL;
-- Fail loudly if any order maps to an unhandled region/nation (source_currency would be NULL and the
-- metric-view fx join would then silently drop that order from the converted measure).
ALTER TABLE orders_currency ALTER COLUMN source_currency SET NOT NULL;
ALTER TABLE orders_currency ADD CONSTRAINT pk_orders_currency PRIMARY KEY(o_orderkey) RELY;
