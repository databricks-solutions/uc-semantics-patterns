-- =====================================================================================================================
-- Currency conversion - exchange rates & region-mapped source currency
--
-- Prerequisite: the TPC-H test dataset must already exist (run /tpc-h.sql first). This script adds the two tables
-- used by the Currency conversion metric views:
--   * exchange_rate   - REAL historical monthly exchange rates per currency pair and rate type
--   * orders_currency - orders enriched with a source currency mapped from the customer's TPC-H region
-- =====================================================================================================================

